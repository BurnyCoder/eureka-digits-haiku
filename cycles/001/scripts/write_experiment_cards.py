"""Write one report card per experiment record; every number is read from results/<id>.json.

Before writing, checks the registration chain recorded in the cycle: every record's protocol_sha256 equals the
current research/protocol.json hash (and research/registration.json), every record's code_sha256 equals the
current study.py hash (and research/core-code.json), and every experiment identifier is unique.
The pilot card (reports/experiment-pilot_regularized_s0.md) was written in the pilot phase and is not regenerated.
Sources: hashlib.sha256 https://docs.python.org/3/library/hashlib.html
Outputs: reports/experiment-<id>.md
"""
from pathlib import Path
import hashlib
import json

root = Path(__file__).resolve().parents[1]


def sha(path):
    """SHA-256 of a file's bytes, the same hash study.py stores in every record."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load(path):
    return json.loads(path.read_text(encoding='utf-8'))


protocol = load(root/'research/protocol.json')
protocol_sha, code_sha = sha(root/'research/protocol.json'), sha(root/'study.py')
assert load(root/'research/registration.json')['protocol_sha256'] == protocol_sha, 'Unregistered protocol change'
assert load(root/'research/core-code.json')['sha256'] == code_sha, 'Code differs from the published core'

records = [load(path) for path in sorted((root/'results').glob('*.json'))]
ids = [record['id'] for record in records]
assert len(ids) == len(set(ids)), 'Duplicate experiment identifiers'
for record in records:
    assert record['protocol_sha256'] == protocol_sha, record['id']
    assert record['code_sha256'] == code_sha, record['id']

for record in records:
    if record['id'].startswith('pilot_'):
        continue
    n = len(record['y_true'])
    correct = sum(t == p for t, p in zip(record['y_true'], record['y_pred']))
    history = record['history']
    final = history[-1] if history else None
    weight_decay = protocol['weight_decay'].get(record['method'], 'not applicable')
    card = f"""# Experiment card: `{record['id']}`

Part of [experiments.md](experiments.md) (registered comparisons, cycle 001). Generated by `scripts/write_experiment_cards.py` from `results/{record['id']}.json`; do not edit by hand.

| Field | Value |
|---|---|
| Method | `{record['method']}` |
| Seed | {record['seed']} |
| Analysis kind | {record['analysis_kind']} |
| Split | {record['split']} (n = {n}) |
| AdamW weight decay | {weight_decay} |
| Test accuracy | {record['accuracy']:.5f} ({correct}/{n}) |
| Final-epoch train loss | {final['train_loss'] if final else 'not applicable'} |
| Final-epoch validation loss | {final['validation_loss'] if final else 'not applicable'} |
| Epochs recorded | {len(history)} |
| Checkpoint | `{record['checkpoint']}` |
| Checkpoint SHA-256 | `{record['checkpoint_sha256']}` |
| Started / finished (UTC) | {record['started_at']} / {record['finished_at']} |
| Wall time | {record['seconds']:.2f} s |
| Device / hardware | {record['device']} / {record['hardware']} |
| Torch / NumPy | {record['torch_version']} / {record['numpy_version']} |
| Protocol SHA-256 | `{record['protocol_sha256']}` |
| Code SHA-256 (`study.py`) | `{record['code_sha256']}` |
| Dataset SHA-256 | `{record['dataset_sha256']}` |

**Expected observation (preregistered text in the record):** {record['expected_observation']}

**Limitations (record text):** {record['limitations']}
"""
    (root/'reports'/f"experiment-{record['id']}.md").write_text(card, encoding='utf-8')
    print(f"wrote reports/experiment-{record['id']}.md")
print(f'checked {len(records)} records: protocol and code hashes match, identifiers unique')
